def parse_json_field(raw, fallback=None):
    if not raw or not raw.strip():
        return fallback if fallback is not None else {}
    try:
        return json.loads(raw)
    except json.JSONDecodeError as exc:
        raise ValueError(f"JSON 格式錯誤：{exc}")

