def compact_ai_text(text, max_chars):
    """Keep AI feedback readable on mobile even when the model exceeds the prompt limit."""
    normalized = " ".join(str(text or "").split()).strip()
    if len(normalized) <= max_chars:
        return normalized

    preview = normalized[:max_chars]
    sentence_end = max(preview.rfind("。"), preview.rfind("！"), preview.rfind("？"))
    if sentence_end >= max_chars // 2:
        return preview[:sentence_end + 1]
    return preview.rstrip("，、；：,. ") + "…"

def safe_generate_text(prompt, fallback_text, timeout=35):
    if not GEMINI_API_KEY:
        return fallback_text

    api_key = GEMINI_API_KEY.strip()
    if api_key.startswith("$env:") or '"' in api_key or "'" in api_key:
        print("Gemini API Key 格式錯誤，請只設定金鑰本身，不要填入環境變數指令")
        return fallback_text

    cache_key = hashlib.sha256(f"{GEMINI_MODEL}|{prompt}".encode("utf-8")).hexdigest()
    if cache_key in GEMINI_CACHE:
        print("Gemini cache hit，使用快取結果")
        return GEMINI_CACHE[cache_key]

    url = f"https://generativelanguage.googleapis.com/v1beta/models/{GEMINI_MODEL}:generateContent"
    headers = {
        "Content-Type": "application/json",
        "x-goog-api-key": api_key,
    }
    payload = {"contents": [{"parts": [{"text": prompt}]}]}
    session = requests.Session()
    session.trust_env = False
    retry_delays_429 = [8]
    retry_delays_5xx = [8]
    max_attempts = 2

    for attempt in range(max_attempts):
        try:
            with gemini_lock:
                r = session.post(url, headers=headers, json=payload, timeout=timeout)

            is_last_attempt = attempt == max_attempts - 1

            if r.status_code == 429:
                if is_last_attempt:
                    break

                retry_after = r.headers.get("Retry-After")
                delay = int(retry_after) if retry_after and retry_after.isdigit() else retry_delays_429[attempt]
                delay = min(delay, 5)

                print(f"Gemini 429 限流，第 {attempt + 1} 次等待 {delay} 秒後重試")
                time.sleep(delay)
                continue

            if r.status_code in [500, 502, 503, 504]:
                if is_last_attempt:
                    break

                delay = retry_delays_5xx[attempt]

                print(f"Gemini 暫時不可用，第 {attempt + 1} 次等待 {delay} 秒後重試: {r.status_code}")
                time.sleep(delay)
                continue

            if 400 <= r.status_code < 500:
                print(f"Gemini REST 設定或請求錯誤: HTTP {r.status_code}")
                break

            r.raise_for_status()
            data = r.json()
            text = data["candidates"][0]["content"]["parts"][0]["text"].strip()

            if text:
                GEMINI_CACHE[cache_key] = text
                return text

            return fallback_text

        except Exception as e:
            print(f"Gemini REST 第 {attempt + 1} 次失敗: {type(e).__name__}")

            if attempt < max_attempts - 1:
                time.sleep(3)

    print("Gemini REST 連續失敗，使用備用回應")
    return fallback_text

